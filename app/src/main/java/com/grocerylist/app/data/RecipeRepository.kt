package com.grocerylist.app.data

import android.util.Log
import com.google.firebase.Firebase
import com.google.firebase.auth.auth
import com.google.firebase.firestore.DocumentSnapshot
import com.google.firebase.firestore.firestore
import com.google.firebase.firestore.snapshots
import com.grocerylist.app.BuildConfig
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.map
import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.sync.withLock
import kotlinx.coroutines.tasks.await
import kotlinx.coroutines.withContext
import org.json.JSONArray
import org.json.JSONObject
import java.net.HttpURLConnection
import java.net.URL

data class Ingredient(val name: String, val quantity: String)

data class Recipe(
    val videoId: String,
    val title: String,
    val totalMinutes: Int,
    val ingredients: List<Ingredient>,
    val steps: List<String>,
    val usesHouseholdItems: List<String>,
    val videoUrl: String,
    val channel: String,
    val thumbnailUrl: String,
)

data class RecipeSet(val generatedAt: Long, val recipes: List<Recipe>)

/**
 * Recipes are generated by the Vercel server (YouTube search + Claude) at most once a day per
 * household, then cached in Firestore so every member sees the same set without paying for it again.
 */
class RecipeRepository(householdId: String) {
    private val doc = Firebase.firestore.collection("households").document(householdId)
        .collection("recipes").document("current")
    private val refreshing = Mutex()

    fun observe(): Flow<RecipeSet?> = doc.snapshots().map(::parse)

    /** Returns quietly if recipes are fresh, there isn't enough history yet, or another refresh is running. */
    suspend fun refreshIfStale(stats: List<ItemStat>) {
        val items = suggestItems(stats, storeId = "", alreadyOnList = emptySet(), now = System.currentTimeMillis(), limit = 15)
            .map { it.displayName }
        if (items.size < MIN_ITEMS) return
        if (!refreshing.tryLock()) return
        try {
            val current = parse(doc.get().await())
            if (current != null && System.currentTimeMillis() - current.generatedAt < REFRESH_INTERVAL_MS) return
            val recipes = fetch(items)
            // An empty result (e.g. a server hiccup) shouldn't wipe out yesterday's recipes.
            if (recipes.length() > 0 || current == null) {
                doc.set(mapOf("generatedAt" to System.currentTimeMillis(), "recipes" to toFirestore(recipes))).await()
            }
        } catch (e: Exception) {
            Log.w(TAG, "Recipe refresh failed", e)
        } finally {
            refreshing.unlock()
        }
    }

    private suspend fun fetch(items: List<String>): JSONArray {
        val token = Firebase.auth.currentUser?.getIdToken(false)?.await()?.token
            ?: error("Not signed in")
        return withContext(Dispatchers.IO) {
            val conn = URL("${BuildConfig.RECIPES_API_URL}/api/recipes").openConnection() as HttpURLConnection
            try {
                conn.requestMethod = "POST"
                conn.connectTimeout = 15_000
                conn.readTimeout = 120_000 // the server runs two Claude calls and several YouTube searches
                conn.doOutput = true
                conn.setRequestProperty("Content-Type", "application/json")
                conn.setRequestProperty("Authorization", "Bearer $token")
                conn.outputStream.use { it.write(JSONObject().put("items", JSONArray(items)).toString().toByteArray()) }
                if (conn.responseCode != 200) {
                    error("Recipe server returned ${conn.responseCode}: ${conn.errorStream?.bufferedReader()?.readText()}")
                }
                JSONObject(conn.inputStream.bufferedReader().readText()).getJSONArray("recipes")
            } finally {
                conn.disconnect()
            }
        }
    }

    private fun toFirestore(recipes: JSONArray): List<Map<String, Any>> = (0 until recipes.length()).map { i ->
        val r = recipes.getJSONObject(i)
        mapOf(
            "videoId" to r.getString("videoId"),
            "title" to r.getString("title"),
            "totalMinutes" to r.optInt("totalMinutes"),
            "ingredients" to r.getJSONArray("ingredients").let { arr ->
                (0 until arr.length()).map { j ->
                    val ing = arr.getJSONObject(j)
                    mapOf("name" to ing.getString("name"), "quantity" to ing.optString("quantity"))
                }
            },
            "steps" to r.getJSONArray("steps").strings(),
            "usesHouseholdItems" to r.optJSONArray("usesHouseholdItems").strings(),
            "videoUrl" to r.getString("videoUrl"),
            "channel" to r.optString("channel"),
            "thumbnailUrl" to r.optString("thumbnailUrl"),
        )
    }

    @Suppress("UNCHECKED_CAST")
    private fun parse(snap: DocumentSnapshot): RecipeSet? {
        if (!snap.exists()) return null
        val raw = snap.get("recipes") as? List<Map<String, Any?>> ?: emptyList()
        return RecipeSet(
            generatedAt = snap.getLong("generatedAt") ?: 0,
            recipes = raw.map { r ->
                Recipe(
                    videoId = r["videoId"] as? String ?: "",
                    title = r["title"] as? String ?: "",
                    totalMinutes = (r["totalMinutes"] as? Number)?.toInt() ?: 0,
                    ingredients = (r["ingredients"] as? List<Map<String, Any?>>).orEmpty().map {
                        Ingredient(it["name"] as? String ?: "", it["quantity"] as? String ?: "")
                    },
                    steps = (r["steps"] as? List<String>).orEmpty(),
                    usesHouseholdItems = (r["usesHouseholdItems"] as? List<String>).orEmpty(),
                    videoUrl = r["videoUrl"] as? String ?: "",
                    channel = r["channel"] as? String ?: "",
                    thumbnailUrl = r["thumbnailUrl"] as? String ?: "",
                )
            },
        )
    }

    private fun JSONArray?.strings(): List<String> =
        if (this == null) emptyList() else (0 until length()).map { getString(it) }

    private companion object {
        const val TAG = "RecipeRepository"
        const val REFRESH_INTERVAL_MS = 24L * 60 * 60 * 1000
        // Fewer regulars than this and the searches are too generic to be useful.
        const val MIN_ITEMS = 3
    }
}
