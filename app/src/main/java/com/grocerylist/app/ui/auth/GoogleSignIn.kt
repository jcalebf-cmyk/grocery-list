package com.grocerylist.app.ui.auth

import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential

class GoogleSignInNotConfigured : Exception("Google sign-in isn't set up yet. Use email for now.")

/**
 * Shows the system Google account picker and returns an ID token for Firebase.
 * `context` must be an Activity. Throws GetCredentialCancellationException if the user backs out.
 */
suspend fun requestGoogleIdToken(context: Context): String {
    // Generated by the google-services plugin once Google sign-in is enabled in Firebase.
    // Looked up by name so the app still builds and runs (email-only) before that.
    val resId = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
    if (resId == 0) throw GoogleSignInNotConfigured()

    val option = GetSignInWithGoogleOption.Builder(context.getString(resId)).build()
    val request = GetCredentialRequest.Builder().addCredentialOption(option).build()
    val credential = CredentialManager.create(context).getCredential(context, request).credential

    if (credential is CustomCredential && credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
        return GoogleIdTokenCredential.createFrom(credential.data).idToken
    }
    error("Unexpected credential type: ${credential.type}")
}
